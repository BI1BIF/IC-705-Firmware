"""Pack APRS artwork and names for the IC-705. Inputs and licenses are in IC705_APRS.md."""

import argparse
import csv
from itertools import groupby
from pathlib import Path
import re

from PIL import Image, ImageDraw


PALETTE = ((0, 0, 0), (23, 26, 34), (66, 75, 86), (119, 129, 139),
           (189, 199, 209), (255, 255, 255), (222, 48, 44), (255, 138, 44),
           (245, 220, 62), (51, 178, 84), (64, 231, 195), (66, 156, 245),
           (49, 74, 190), (167, 94, 212), (236, 123, 178), (155, 103, 68))


def indexed_pixel(pixel):
    r, g, b, alpha = pixel
    if alpha < 48:
        return 0
    return min(range(1, len(PALETTE)), key=lambda i: sum(
        (p - q) ** 2 for p, q in zip((r, g, b), PALETTE[i])))


def clean_name(text):
    text = re.split(r"\s+(?:\(|\*|https?://|was \\)", text)[0].strip().rstrip(". ,)")
    return text.encode("ascii", "ignore").decode().replace("\\", "/").replace('"', "'")


def new_icons():
    power = Image.new("RGBA", (24, 24))
    draw = ImageDraw.Draw(power)
    draw.rounded_rectangle((2, 2, 21, 21), 4, fill=PALETTE[2], outline=PALETTE[4], width=1)
    draw.polygon(((13, 4), (6, 13), (11, 13), (9, 20), (18, 10), (13, 10), (15, 4)), fill=PALETTE[8])
    gps = Image.new("RGBA", (24, 24))
    draw = ImageDraw.Draw(gps)
    draw.ellipse((4, 4, 19, 19), fill=PALETTE[12], outline=PALETTE[11], width=2)
    draw.line(((11, 2), (11, 8)), fill=PALETTE[5], width=2)
    draw.line(((11, 15), (11, 21)), fill=PALETTE[5], width=2)
    draw.line(((2, 11), (8, 11)), fill=PALETTE[5], width=2)
    draw.line(((15, 11), (21, 11)), fill=PALETTE[5], width=2)
    draw.ellipse((10, 10, 13, 13), fill=PALETTE[5])
    return {r"\%": power, "\\\\": gps}


def generate(inputs, output):
    with (inputs / "symbols.csv").open(encoding="utf-8", newline="") as stream:
        names = {row["CODE"]: clean_name(row["DESCRIPTION"])
                 for row in csv.DictReader(stream, delimiter="\t") if row["DESCRIPTION"]}
    names.update({r"\%": "Power and Energy", r"\=": "Rail", r"\Y": "Radio",
                  "\\\\": "GPS Device"})
    alternate_art = {r"\=": "/="}
    updated_art = new_icons()

    updates = (inputs / "symbols-new.txt").read_bytes().decode("cp1252")
    updates = updates.split("WEATHER SYMBOLS")[0]
    overlay_names = {m[1]: clean_name(m[2]) for m in re.finditer(
        r"^\s*([0-9A-Z][!-~])\s+(?:=\s*|-\s+)([^\r\n]+)", updates, re.M)}
    overlay_names.update({"BE": "Blowing Snow", "DE": "Blowing Dust or Sand", "FE": "Fog",
                          "HE": "Haze", "SE": "Smoke", "R&": "Receive-only iGate",
                          "T&": "One-hop TX iGate", "2&": "Two-hop TX iGate"})

    stock = set()
    for prefix, codes in (("/", "!#&'+-./:;<=>CEKLOPRSTUVWXY[\\^_`abfghjknprsuvy"),
                          ("\\", "#&-.0;>LSUWY^_acghjmnostuvx")):
        stock.update(prefix + code for code in codes)
    images = [Image.open(inputs / f"aprs-symbols-24-{i}.png").convert("RGBA") for i in range(2)]
    packed = bytearray(b"\x00")
    art = {}
    for table, prefix in enumerate("/\\"):
        for n in range(94):
            code = prefix + chr(n + 33)
            if code not in names or code in stock or code in alternate_art:
                continue
            x, y = n % 16 * 24, n // 16 * 24
            icon = updated_art[code] if code in updated_art else images[table].crop((x, y, x+24, y+24))
            pixels = [indexed_pixel(icon.getpixel((col, row))) for row in range(24) for col in range(24)]
            assert any(pixels), code
            art[code] = len(packed)
            for color, group in groupby(pixels):
                count = len(list(group))
                while count:
                    run = min(count, 16)
                    packed.append((run - 1) << 4 | color)
                    count -= run

    assert len(packed) < 65536
    with output.open("w", encoding="ascii", newline="\n") as stream:
        print("/* Generated by tools/make_705_aprs_symbols.py. See docs/IC705_APRS.md. */", file=stream)
        print("static const uint16_t extra_palette[] = {", file=stream)
        print("    " + ", ".join(f"0x{(r>>3)<<11 | (g>>2)<<5 | b>>3:04x}" for r, g, b in PALETTE), file=stream)
        print("};\nstatic const uint8_t extra_pixels[] = {", file=stream)
        for i in range(0, len(packed), 16):
            print("    " + ", ".join(f"0x{byte:02x}" for byte in packed[i:i+16]) + ",", file=stream)
        print("};\nstatic const struct base_symbol base_symbols[188] = {", file=stream)
        for code, name in sorted(names.items()):
            if len(code) != 2 or code[0] not in "/\\" or not name:
                continue
            n = (94 if code[0] == "\\" else 0) + ord(code[1]) - 33
            alias = alternate_art.get(code, "\x00\x00")
            alias = ord(alias[0]) << 8 | ord(alias[1])
            print(f'    [{n}] = {{"{name}", {art.get(code, 0)}, 0x{alias:04x}}},', file=stream)
        print("};\nstatic const struct overlay_symbol overlay_symbols[] = {", file=stream)
        for code, name in sorted(overlay_names.items()):
            if name:
                print(f'    {{"{name}", 0x{ord(code[0]):02x}{ord(code[1]):02x}}},', file=stream)
        print("};", file=stream)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generate(args.inputs, args.output)
