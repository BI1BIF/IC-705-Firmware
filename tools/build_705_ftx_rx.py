def package():
    from zipfile import ZIP_DEFLATED, ZipFile

    source = OUT / "bench-rx.dat"
    data = source.read_bytes()
    digest = sha256(data).hexdigest()
    for name in (
        "layout",
        "rebuild",
        "station",
        "exchange",
        "sstv-tx",
        "history",
        "ui",
        "installed",
        "offsets",
        "scheduler",
        "tx-panel",
        "restart",
        "remote",
        "remote-panel",
        "panel-audio",
        "compact/panel-audio",
        "remote-audio/panel-audio",
        "dial",
        "other-receivers",
    ):
        require(
            json.loads((OUT / (name + ".json")).read_text())["dat_sha256"] == digest,
            "verification belongs to a different candidate: " + name,
        )
    memory = json.loads((OUT / "memory.json").read_text())
    delayed = json.loads((OUT / "delayed-wakes.json").read_text())
    require(
        delayed["tx1"]["dat_sha256"] == memory["tx1"]["dat_sha256"] == digest,
        "memory or audio-pressure test is for another DAT",
    )
    recovery = json.loads((OUT / "worker-recovery.json").read_text())
    require(all(recovery[mode]["dat_sha256"] == digest for mode in ("FT8","FT4")),
            "worker recovery test is for another DAT")
    weak = json.loads((OUT / "weak.json").read_text())
    require(
        weak["tx1"]["dat_sha256"] == weak["tx1_compact"]["dat_sha256"] == digest
        and len(weak["samples"]) == 31,
        "weak-signal comparison belongs to a different candidate",
    )
    lab = ROOT / ".analysis"
    notices = [
        ("ft8_lib (kgoba)", LIB / "LICENSE"),
        ("Noto Sans SC (FT subset and coverage masks)", CODE / "font/Noto-OFL.txt"),
        ("KISS FFT", CODE / "kissfft-LICENSE.txt"),
        ("Flag thumbnails (lipis/flag-icons)", lab / "ftx-flags/LICENSE"),
        ("DXCC metadata (FT8CN)", lab / "ftx-cn-ref/LICENSE"),
        ("Country Files (Jim Reisert, AD1C)", CODE / "cty-LICENSE.txt"),
    ]
    notice = "\n\n".join(
        name + "\n" + path.read_text(encoding="utf8") for name, path in notices
    )
    notice += "\nMaidenhead(mh) data copyright 2020 Stephen Loomis and Henry Forte.\n"
    target = OUT / "705J140-FT8-FT4-TX2j-SD.zip"
    with ZipFile(target, "w", compression=ZIP_DEFLATED) as archive:
        archive.writestr("IC-705/705J140.dat", data)
        archive.writestr("THIRD-PARTY.txt", notice)
    with ZipFile(target) as archive:
        require(
            archive.namelist() == ["IC-705/705J140.dat", "THIRD-PARTY.txt"]
            and archive.read("THIRD-PARTY.txt").decode() == notice
            and archive.read(archive.namelist()[0]) == data,
            "SD archive round trip failed",
        )
    print(target, sha256(target.read_bytes()).hexdigest())


