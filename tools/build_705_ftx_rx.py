def assemble(base, sections, sym):
    image = bytearray(base)

    def read(a, n):
        return bytes(image[a - BASE : a - BASE + n])

    def put(a, v):
        image[a - BASE : a - BASE + len(v)] = v

    def replace(a, old, new):
        require(word(image, a) == old, f"unexpected word at {a:#x}")
        put(a, pack("<I", new))

    require(
        BASE + len(image) == TAIL
        and read(DUP, 277 * STRIDE) == read(PICKER_TABLE, 277 * STRIDE),
        "selector duplicate differs",
    )
    menu = bytearray(read(DUP,317*STRIDE))
    for row, fields in [
        (
            277,
            {
                12: "ftx_select",
                32: "ftx_choice",
                48: "ftx_menu_title",
                56: "ftx_menu_title",
                68: "ftx_items",
            },
        ),
        (278, {52: "ftx_label8", 60: "ftx_label8"}),
        (279, {52: "ftx_label4", 60: "ftx_label4"}),
    ]:
        record = bytearray(read(DUP + row * STRIDE, STRIDE))
        for off, name in fields.items():
            record[off : off + 4] = pack("<I", sym[name])
        menu.extend(record)
    # Cold initialization already copies the OEM descriptors. Encode extension
    # rows as literals or copies from descriptors already restored in RAM.
    packed = pack_init_tail(menu, 277 * STRIDE)
    mode_start = DUP + 277 * STRIDE
    label_address = DUP + 317 * STRIDE - len(packed)
    put(label_address,packed)
    for name, (a, data) in sections.items():
        if name == ".logram":
            require(a == FT_DATA_RAM+0x1d00 and a+len(data)<=SSTV_BSS,"journal RAM overflow")
            continue
        if name == ".ftdata":
            require(a == FT_DATA_RAM and len(data) <= 0x1d00, "FT constants exceed reserved RAM")
            (OUT / "ftdata.bin").write_bytes(data)
            continue
        require(
            name == ".panel" and 0x20369ac0 <= a and a+len(data) <= 0x2036a000 and not any(read(a,len(data)))
            or name == ".extra" and mode_start <= a and a+len(data) <= label_address
            or DUP <= a
            and a + len(data) <= 0x20373de4
            or STATION <= a
            and a + len(data) <= TAIL
            or TAIL <= a
            and a + len(data) <= END,
            f"{name} outside its two application regions",
        )
        if a > BASE + len(image):
            image.extend(bytes(a - BASE - len(image)))
        put(a, data)
    for addr in PICKER_REFERENCES:
        replace(addr, DUP, MENU)
    replace(0x202D3A64, HEAP_END, FT_DATA_RAM)
    for site, old, name in (
        (0x20379FA4, 0x2037625C, "ft_tx_source_arm"),
        (0x20379F84, 0x20376320, "ft_tx_requested_arm"),
        (0x200FFEB0, 0x20376F10, "ft_tx_mod_block_arm"),
    ):
        replace(
            site, branch(site, old, 0xEB000000), branch(site, sym[name], 0xEB000000)
        )
    cw_call = 0x2036E7F8
    replace(
        cw_call,
        branch(cw_call, 0x2036CDC8, 0xEB000000),
        branch(cw_call, sym["ftx_cw_bridge"], 0xEB000000),
    )
    for name, addr in SITES.items():
        replace(addr, word(base, addr), branch(addr, sym["ftx_" + name + "_bridge"]))
    while len(image) % 4:
        image.append(0)
    desc = BASE + len(image)
    image.extend(read(0x2000530C, 48))
    image.extend(pack("<4I", PICKER_TABLE, MENU, 277*STRIDE, 0x200052EC))
    image.extend(pack("<4I", label_address, MENU + 277*STRIDE, 0, sym["ft_restore_modes"]))
    replace(0x200052E4, 0x2000530C, desc)
    replace(0x200052E8, 0x2000533C, desc + 80)
    require(BASE + len(image) <= END, "menu initialization exceeds application bounds")
    cpu = machine(bytes(image))
    cpu.mem_write(FT_DATA_RAM, b"\xa5" * (MENU - FT_DATA_RAM))
    cpu.emu_start(0x200052C9, 0x200052A8, count=12000000)
    from tools.emulate_705 import arm

    require(
        cpu.reg_read(arm.UC_ARM_REG_PC) == 0x200052A8
        and not any(cpu.mem_read(FT_DATA_RAM, MENU - FT_DATA_RAM))
        and bytes(cpu.mem_read(MENU, 317 * STRIDE))
        == base[DUP - BASE : DUP - BASE + 317 * STRIDE]
        and bytes(cpu.mem_read(MENU + 317 * STRIDE, 3 * STRIDE))
        == menu[317*STRIDE:],
        "original scatter-load did not reproduce all menus",
    )
    return bytes(image)


def add_atlas(data, blob):
    from hashlib import md5

    from tools.decode_705_main import checked_group_a
    from tools.replay_705_stock_install import load_a

    _, group = checked_group_a(data)
    digest = sha256(bytes(decode_main(data)[1])).hexdigest()
    _, plain = load_a(data, digest)
    start, end = group["offset"], group["end_exclusive"]
    split = unpack_from("<I", blob, 16)[0]
    require(
        INDEX_OFFSET + split < 0x262000 and PIXEL_OFFSET + len(blob) - split < 0x600000,
        "atlas overlaps original resources",
    )
    result = bytearray(data)
    expected = bytearray(plain)
    constants=(OUT / "ftdata.bin").read_bytes()
    glyphs = (OUT / "glyphs.bin").read_bytes()
    require(FT_DATA_OFFSET+len(constants)<GLYPH_OFFSET and GLYPH_OFFSET+len(glyphs)<INDEX_OFFSET, "FT resource blocks overlap")
    faces=(OUT / "key-faces.bin").read_bytes()
    require(KEY_OFFSET+len(faces)<0x26b000, "key artwork exceeds reserved space")
    for at, chunk in ((KEY_OFFSET,faces),(FT_DATA_OFFSET, constants), (GLYPH_OFFSET, glyphs), (INDEX_OFFSET, blob[:split]), (PIXEL_OFFSET, blob[split:])):
        require(
            plain[at : at + len(chunk) + 1] == b"\xff" * (len(chunk) + 1),
            "atlas region occupied",
        )
        expected[at : at + len(chunk)] = chunk
        prev = plain[at - 1]
        for i, value in enumerate(chunk + b"\xff", start + at):
            result[i] = value ^ ((prev + i - 0x19) & 255)
            prev = value
    result[end : end + 16] = md5(result[start:end], usedforsecurity=False).digest()
    _, actual = load_a(bytes(result), digest)
    require(actual == expected, "atlas DAT round trip failed")
    return bytes(result)


