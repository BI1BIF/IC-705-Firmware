def relink_sstv(base):
    from os import environ
    from pathlib import Path
    from tools.probe_705_sstv_arm import build as sstv_build

    clang = environ.get(
        "IC705_CLANG",
        str(
            Path.home()
            / ".codex/ndi-android-toolchain/sdk/ndk/27.2.12479018/toolchains/llvm/prebuilt/windows-x86_64/bin/clang.exe"
        ),
    )
    options = dict(
        base=0x20374840,
        cw_pcm=0x2036A09C,
        diagnostics=True,
        robot_sync=True,
        basic=True,
        late_join=True,
        tx_study=True,
    )
    original, old = sstv_build(OUT / "sstv-original", clang, limit=TAIL, **options)
    require(
        base[options["base"] - BASE : options["base"] - BASE + len(original)]
        == original
        and old["end_rx"] == TAIL,
        "SSTV source differs from the installed baseline",
    )
    data, new = sstv_build(
        OUT / "sstv", clang, bss_address=SSTV_BSS, limit=MENU, **options
    )
    require(
        new["end_rx"] == MENU
        and len(original) == len(data)
        and all(
            new[k] == (v + SSTV_BSS - STATION if STATION <= v <= TAIL else v)
            for k, v in old.items()
            if not k.startswith("$")
        ),
        "SSTV exported address changed unexpectedly",
    )
    image = bytearray(base)
    image[options["base"] - BASE : options["base"] - BASE + len(data)] = data
    # These records are generated by the combined CW/SSTV menu builder,
    # outside the SSTV ELF. History labels exist in two language columns.
    menu_state = {
        DUP + row * STRIDE + 32: (name, 0)
        for row, name in (
            (280, "sstv_choice"),
            (283, "sstv_archive_choice"),
            (293, "sstv_tx_choice"),
        )
    }
    for i in range(8):
        for column in (52, 60):
            menu_state[DUP + (285 + i) * STRIDE + column] = ("archive_names", 16 * i)
    from struct import iter_unpack

    found = {
        BASE + 4 * i
        for i, (v,) in enumerate(iter_unpack("<I", base[: options["base"] - BASE]))
        if STATION <= v < TAIL
    }
    require(
        found == set(menu_state),
        "unaccounted external reference to relocated SSTV state",
    )
    for at, (name, offset) in menu_state.items():
        require(
            word(base, at) == old[name] + offset, "unexpected SSTV selector pointer"
        )
        image[at - BASE : at - BASE + 4] = pack("<I", new[name] + offset)
    return bytes(image)


